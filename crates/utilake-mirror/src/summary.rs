//! The map folded into patterns, small enough to commit and read.
//!
//! Every run of digits in a name becomes `{n}`, n its length, so the 207
//! month folders of the archive are one line `MMSDM_{4}_{2}/`, and the
//! files of a table across every month are one line too. Each pattern
//! shows how many names it stands for, their bytes, and the first and last
//! of them.

use std::borrow::Cow;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::BufRead as _;
use std::path::Path;

use serde::Deserialize;

use crate::error::MirrorError;
use crate::map::{NodeKind, State, human};

#[derive(Deserialize)]
struct Line<'a> {
    #[serde(borrow)]
    path: Cow<'a, str>,
    kind: NodeKind,
    size: Option<u64>,
    state: Option<State>,
}

#[derive(Default)]
struct Pattern {
    count: u64,
    bytes: u64,
    not_archived: u64,
    first: String,
    last: String,
}

/// `name` with every run of ASCII digits as `{n}`, n the run's length.
pub fn fold(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut run = 0usize;
    for c in name.chars() {
        if c.is_ascii_digit() {
            run += 1;
            continue;
        }
        if run > 0 {
            let _ = write!(out, "{{{run}}}");
            run = 0;
        }
        out.push(c);
    }
    if run > 0 {
        let _ = write!(out, "{{{run}}}");
    }
    out
}

/// The pattern summary of the map at `map_ndjson`, as Markdown.
pub fn summary(map_ndjson: &Path) -> Result<String, MirrorError> {
    let file = std::fs::File::open(map_ndjson).map_err(MirrorError::io(map_ndjson))?;
    let reader = std::io::BufReader::with_capacity(1 << 20, file);
    // Keyed by folded segments, each marked with what holds the next one:
    // `/` a folder, `!` a zip; the last marked by the node's own kind.
    let mut patterns: BTreeMap<Vec<String>, Pattern> = BTreeMap::new();
    let mut key: Vec<String> = Vec::new();
    let mut totals = Pattern::default();
    for (i, line) in reader.lines().enumerate() {
        let line = line.map_err(MirrorError::io(map_ndjson))?;
        let node: Line<'_> = serde_json::from_str(&line).map_err(|e| MirrorError::Record {
            path: map_ndjson.display().to_string(),
            line: i as u64 + 1,
            message: e.to_string(),
        })?;
        key.clear();
        let mut start = 0;
        for (at, sep) in node.path.match_indices(['/', '!']) {
            key.push(format!("{}{sep}", fold(&node.path[start..at])));
            start = at + 1;
        }
        let last = &node.path[start..];
        let mark = match node.kind {
            NodeKind::Dir => "/",
            NodeKind::Zip => "!",
            NodeKind::File => "",
        };
        key.push(format!("{}{mark}", fold(last)));
        let size = if node.kind == NodeKind::Dir {
            0
        } else {
            node.size.unwrap_or(0)
        };
        let missing = u64::from(node.state == Some(State::NotArchived));
        let p = patterns.entry(key.clone()).or_default();
        p.count += 1;
        p.bytes += size;
        p.not_archived += missing;
        // Totals over the files nemweb lists or listed, which carry a state;
        // what a zip holds is in the zip's bytes already.
        if node.state.is_some() {
            totals.count += 1;
            totals.bytes += size;
            totals.not_archived += missing;
        }
        if p.first.is_empty() || last < p.first.as_str() {
            last.clone_into(&mut p.first);
        }
        if last > p.last.as_str() {
            last.clone_into(&mut p.last);
        }
    }
    Ok(render(&patterns, &totals))
}

fn render(patterns: &BTreeMap<Vec<String>, Pattern>, totals: &Pattern) -> String {
    let mut out = String::from(
        "# nemweb map\n\n\
         Generated by `nemweb-mirror summary` from the map of the mirror \
         (`nemweb-mirror map`); do not edit.\n\n\
         Every run of digits in a name is `{n}`, n its length. A line is a \
         pattern: how many names it stands for, their bytes, and the first and \
         last of them. A folder ends in `/`, a zip in `/ (zip)`, and what a zip \
         holds is indented under it.\n\n",
    );
    let _ = writeln!(
        out,
        "{} patterns over {} files of nemweb, {}{}.\n\n```text",
        patterns.len(),
        totals.count,
        human(totals.bytes),
        missing(totals.not_archived)
    );
    for (key, p) in patterns {
        let last = &key[key.len() - 1];
        let (name, shown) = match last.as_bytes().last() {
            Some(b'/') => (
                &last[..last.len() - 1],
                format!("{}/", &last[..last.len() - 1]),
            ),
            Some(b'!') => (
                &last[..last.len() - 1],
                format!("{}/ (zip)", &last[..last.len() - 1]),
            ),
            _ => (last.as_str(), last.clone()),
        };
        let _ = write!(out, "{}{shown}", "  ".repeat(key.len() - 1));
        let is_dir = last.ends_with('/');
        if p.count > 1 {
            let _ = write!(out, "  × {}", p.count);
        }
        if !is_dir {
            let _ = write!(out, "  {}", human(p.bytes));
        }
        if p.count > 1 {
            let _ = write!(out, "  {} … {}", p.first, p.last);
        } else if name != p.first {
            let _ = write!(out, "  {}", p.first);
        }
        out.push_str(&missing(p.not_archived));
        out.push('\n');
    }
    out.push_str("```\n");
    out
}

fn missing(n: u64) -> String {
    if n == 0 {
        String::new()
    } else {
        format!(" ({n} not downloaded)")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn folds_every_run_of_digits() {
        assert_eq!(fold("MMSDM_2026_09"), "MMSDM_{4}_{2}");
        assert_eq!(
            fold("PUBLIC_ARCHIVE#P5MIN_X#FILE01#202609010000.zip"),
            "PUBLIC_ARCHIVE#P{1}MIN_X#FILE{2}#{12}.zip"
        );
        assert_eq!(fold("2026"), "{4}");
        assert_eq!(fold("README.txt"), "README.txt");
        assert_eq!(fold(""), "");
    }

    #[test]
    fn folds_the_map_into_patterns() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("map.ndjson");
        let lines = [
            r#"{"path":"h","kind":"dir"}"#,
            r#"{"path":"h/A","kind":"dir"}"#,
            r#"{"path":"h/A/2025","kind":"dir"}"#,
            r#"{"path":"h/A/2025/d_20250101.zip","kind":"zip","size":10,"state":"archived"}"#,
            r#"{"path":"h/A/2025/d_20250101.zip!x_0001.csv","kind":"file","size":40,"compressed":9}"#,
            r#"{"path":"h/A/2025/d_20250101.zip!x_0002.csv","kind":"file","size":50,"compressed":9}"#,
            r#"{"path":"h/A/2025/d_20250102.zip","kind":"zip","size":12,"state":"archived"}"#,
            r#"{"path":"h/A/2026","kind":"dir"}"#,
            r#"{"path":"h/A/2026/d_20260101.zip","kind":"zip","size":7,"state":"not_archived"}"#,
            r#"{"path":"h/A/README.txt","kind":"file","size":3,"state":"archived"}"#,
        ];
        std::fs::write(&p, lines.join("\n") + "\n").unwrap();
        let md = summary(&p).unwrap();
        let expected = "\
6 patterns over 4 files of nemweb, 32 B (1 not downloaded).

```text
h/
  A/
    README.txt  3 B
    {4}/  × 2  2025 … 2026
      d_{8}.zip/ (zip)  × 3  29 B  d_20250101.zip … d_20260101.zip (1 not downloaded)
        x_{4}.csv  × 2  90 B  x_0001.csv … x_0002.csv
```
";
        assert!(md.ends_with(expected), "{md}");
        assert!(md.starts_with("# nemweb map\n"));

        std::fs::write(&p, "{\"path\":1}\n").unwrap();
        let d = crate::diag::Diagnose::diagnostic(&summary(&p).unwrap_err());
        assert_eq!(
            (d.code.as_ref(), d.line),
            ("mirror.record_corrupt", Some(1))
        );
        let d = crate::diag::Diagnose::diagnostic(&summary(&dir.path().join("x")).unwrap_err());
        assert_eq!(d.code, "mirror.io");
    }
}
